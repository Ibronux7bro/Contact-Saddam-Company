// 🌓 دالة تطبيق السمة (ليلي / نهاري)
function setTheme(theme) {
    document.documentElement.setAttribute('data-theme', theme);
    localStorage.setItem('saddam_theme', theme);

    const themeBtn = document.getElementById('theme-toggle-btn');
    if (themeBtn) {
        themeBtn.innerHTML = theme === 'light' ? '<i class="fa-solid fa-moon"></i>' : '<i class="fa-solid fa-sun"></i>';
        themeBtn.setAttribute('title', theme === 'light' ? 'تفعيل الوضع الليلي' : 'تفعيل الوضع النهاري');
    }
}

// 🌐 دالة تطبيق اللغة الفورية
function setLanguage(lang) {
    document.documentElement.setAttribute('lang', lang);
    document.documentElement.setAttribute('dir', lang === 'ar' ? 'rtl' : 'ltr');
    localStorage.setItem('saddam_lang', lang);

    const langBtn = document.getElementById('lang-toggle-btn');
    if (langBtn) {
        langBtn.innerHTML = lang === 'ar' ? '<i class="fa-solid fa-globe"></i> English' : '<i class="fa-solid fa-globe"></i> العربية';
    }

    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang] && translations[lang][key]) {
            const icon = el.querySelector('i');
            if (icon) {
                const iconHTML = icon.outerHTML;
                el.innerHTML = iconHTML + ' ' + translations[lang][key];
            } else {
                el.textContent = translations[lang][key];
            }
        }
    });
}

// الأحداث والتنفيذ الفوري عند التحميل
document.addEventListener('DOMContentLoaded', () => {
    // 1. تفعيل السمة (الليلي / النهاري)
    const savedTheme = localStorage.getItem('saddam_theme') || 'dark';
    setTheme(savedTheme);

    const themeBtn = document.getElementById('theme-toggle-btn');
    if (themeBtn) {
        themeBtn.onclick = function(e) {
            e.preventDefault();
            const currentTheme = document.documentElement.getAttribute('data-theme') || 'dark';
            const nextTheme = currentTheme === 'dark' ? 'light' : 'dark';
            setTheme(nextTheme);
        };
    }

    // 2. تفعيل اللغة
    const savedLang = localStorage.getItem('saddam_lang') || 'ar';
    setLanguage(savedLang);

    const langBtn = document.getElementById('lang-toggle-btn');
    if (langBtn) {
        langBtn.onclick = function(e) {
            e.preventDefault();
            const current = document.documentElement.getAttribute('lang') || 'ar';
            const nextLang = current === 'ar' ? 'en' : 'ar';
            setLanguage(nextLang);
        };
    }

    // 3. مفتاح الإدارة إخفاء/إظهار القطاع الصناعي
    const toggleSwitch = document.getElementById('industrial-toggle');
    const industrialNav = document.getElementById('nav-industrial');

    if (toggleSwitch) {
        const savedState = localStorage.getItem('saddam_show_industrial');
        if (savedState === 'false') {
            toggleSwitch.checked = false;
            if (industrialNav) industrialNav.style.display = 'none';
        } else {
            toggleSwitch.checked = true;
            if (industrialNav) industrialNav.style.display = 'block';
        }

        toggleSwitch.addEventListener('change', (e) => {
            if (e.target.checked) {
                if (industrialNav) industrialNav.style.display = 'block';
                localStorage.setItem('saddam_show_industrial', 'true');
            } else {
                if (industrialNav) industrialNav.style.display = 'none';
                localStorage.setItem('saddam_show_industrial', 'false');
            }
        });
    }

    // 4. تحديد رابط الصفحة الحالية
    const currentPath = window.location.pathname.split('/').pop() || 'index.html';
    const navLinks = document.querySelectorAll('.nav-links a');
    navLinks.forEach(link => {
        const href = link.getAttribute('href');
        if (href === currentPath) {
            link.classList.add('active');
        } else {
            link.classList.remove('active');
        }
    });
});
